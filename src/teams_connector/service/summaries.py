"""Teams' AI summaries of meetings, read when a request asks for them and never kept.

A summary is generated by AI and can be wrong, so every place it appears labels it; the transcript and the
messages are the record. Three readers use this service: exports, get_messages and transcript search. Each
reads a meeting's summary only for the meetings its own result returns.
"""

from __future__ import annotations

from dataclasses import dataclass

from teams_connector.domain.errors import AuthenticationRequired, ConnectorError
from teams_connector.domain.models import Message, RecordingRef
from teams_connector.remote.ports import MeetingSummaryReader

SUMMARY_LABEL = "AI summary from Teams (generated by AI; may be inaccurate):"
SUMMARY_UNAVAILABLE = "AI summary from Teams could not be read."


@dataclass(frozen=True)
class SummaryRead:
    """One read: Teams' summary text, or None for no summary, and whether the read failed."""

    text: str | None
    failed: bool


class MeetingSummaries:
    """Entry point for the summaries. Every call asks Teams; nothing is cached."""

    def __init__(self, reader: MeetingSummaryReader) -> None:
        self._reader = reader

    async def read(self, recording: RecordingRef) -> SummaryRead:
        """The meeting's summary now. A read Teams refuses is reported as failed, not raised, so the result it
        belongs to stays usable. Authentication still raises."""
        try:
            return SummaryRead(text=await self._reader.summary(recording), failed=False)
        except AuthenticationRequired:
            raise
        except ConnectorError:
            return SummaryRead(text=None, failed=True)

    async def add_to_message(self, message: Message, *, include_transcripts: bool) -> None:
        """Put the AI summary after each transcript marker in the message's text.

        A meeting Teams has no summary for keeps its marker alone. A read that failed says so. Without the
        transcript file, the marker says so instead, and the summary stays in the text."""
        for attachment in message.attachments:
            if attachment.source != "transcript" or attachment.recording is None:
                continue
            marker = f"[Transcript: {attachment.name}]"
            read = await self.read(attachment.recording)
            if read.failed:
                block = SUMMARY_UNAVAILABLE
            elif read.text is None:
                continue
            else:
                block = f"{SUMMARY_LABEL}\n{read.text}"
            head = marker if include_transcripts else f"[Transcript not included: {attachment.name}]"
            message.text = message.text.replace(marker, f"{head}\n{block}")
