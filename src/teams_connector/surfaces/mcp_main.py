"""MCP server over stdio: thin tools over the shared service (architecture, "MCP tools").

One process per agent session. Nothing touches the network until the first tool call. Every tool is
read-only except send_message and delete_messages.
"""

from __future__ import annotations

import asyncio
import functools
import logging
import time
from collections.abc import Awaitable, Callable
from datetime import datetime
from typing import Annotated, Any

from m365_auth import status_report
from mcp.server.fastmcp import Context, FastMCP
from mcp.types import ToolAnnotations
from pydantic import Field

from teams_connector.bootstrap import AppContext, Services
from teams_connector.domain.errors import InvalidRequest
from teams_connector.domain.models import (
    ChatKind,
    ChatPage,
    ChatSearchResult,
    DeleteResult,
    DownloadedFiles,
    ExportArtifact,
    ExportFormat,
    ExportProgress,
    ExportRequest,
    MessagePage,
    MessageSearchResult,
    PresenceResult,
    SendResult,
    TranscriptSearchResult,
)
from teams_connector.domain.time import optional_utc

log = logging.getLogger(__name__)

INSTRUCTIONS = """\
Read access to the signed-in user's Microsoft Teams chats and team channels, plus one explicitly \
authorized message-send tool.

- Finding conversations: list_chats lists chats and channels by recent activity (kind: one_on_one, \
group, meeting, channel, or self for the user's own notes chat). search_chats finds conversations by \
name, and with refresh by the members Teams matches for a plain name or email; read its coverage.
- Reading: get_messages returns a conversation's history newest pages first, oldest first within a \
page, with optional since/until and a total message_limit. Follow `cursor` for older messages. A \
channel's history comes as threads (a post with its replies) by latest activity, each in time order; \
for a channel, message_limit keeps the messages of the most recently active threads. A \
page holds whole messages up to max_chars (at least one), so no message text is cut. \
is_self marks the user's own messages: use it rather than matching names.
- Searching message content: search_messages takes terms (1 to 25 phrases; a message matches when any \
term matches), optionally scoped by conversation_ids and since/until. Each term is one phrase, matched on \
whole words and word prefixes; it is never split on its spaces or read as query syntax. Hits are pointers: \
message_id is the id get_messages reads, and conversation_id is set when it matches a known chat. total is \
approximate. Read coverage before treating results as complete.
- Exporting: export_chats returns a local artifact path. One conversation with no attachment saved is a \
plain .txt/.jsonl file; anything else is one .zip with each conversation's file at its root and its \
attachments in a folder named after that file (no .zip inside it). Attachments are included by \
default; set include_attachments=false to omit them. Date bounds and latest-N message_limit apply per \
conversation; export fetches the selected history, \
so a long selection takes a while. Read the returned file path with your file tools.
- Presence: get_presence reads the other person's availability in a one-on-one chat only. It is read-only, \
and when it returns no presence it says why.
- Attachments: download_attachment saves the files a message names (its shared files and pasted images, \
shown as [File: name] and [Image: name] markers) and returns their local paths. A meeting's Loop notes \
show as [Meeting notes] and a link; download_attachment (as "Meeting notes.txt") and exports read the live \
page and keep its agenda, notes and tasks, unless include_summaries is false. Pass the message_id from \
get_messages, or the message's sent_at time instead.
- Transcripts: a meeting recording whose transcript Teams made shows [Transcript: title] in get_messages. \
download_attachment (as "title") and exports (include_transcripts, on by default; the transcripts folder) \
save it as text with speakers and times. search_transcripts finds words said in meetings: with \
conversation_ids it reads those chats' recordings and is complete unless a transcript could not be read or \
the limit was reached; without them it ranks videos Graph's search returns, keeps only those a meeting chat \
holds, and is never complete. Exports, get_messages and search_transcripts also carry Teams' AI summary of \
each transcribed meeting (include_summaries, on by default). It is generated by AI and can be wrong, so use \
it to judge whether the full transcript is needed, not as the record. To save context tokens, read the \
summary first and open full transcript files only when their detail or verification is needed. \
get_messages includes summaries without downloading transcript files. For exports without full \
transcripts, set include_transcripts=false and include_summaries=true; both remain true by default. \
Use download_attachment to retrieve a full transcript later if needed.
- Messages are read from Teams on each call; nothing is kept locally. Messages with is_deleted=true were \
deleted in Teams, and Teams keeps no text for them; edited ones show their newest text.
- Times are UTC; a date-time without an offset is taken as UTC.
- Sending: never call send_message unless the user explicitly authorized sending that content to that \
chat, in the current request or by confirming after you asked. If authorization is missing or \
ambiguous, ask and wait. One authorization is not ongoing consent. Search, summaries and exports \
never imply permission to send. A send whose outcome is unknown is never resent: check the chat \
before trying again.
- Pass text (plain, escaped) or html (sent as written: bold, lists, links, code) to send_message, never \
both. Active HTML (scripts, forms, event handlers, javascript: links), embedded media, declarations and \
unfinished markup are refused. To show pictures, pass PNG or JPEG paths in images: in html, \
<img src="file name"> places one; images not placed follow the text. Larger or other images go in files.
- Deleting: delete_messages soft-deletes the user's own messages in one chat (never anyone else's; those \
are skipped). Before calling it, list what will be deleted (the chat, how many messages, the first and \
last with their time and text) and get the user's explicit yes for that whole set; one yes covers the set, \
not later deletes. Never delete without that confirmation, even when asked to tidy up or undo a send. \
A delete whose outcome is unknown is never resent: check uncertain ones with get_messages (a deleted \
message shows is_deleted) before trying again. Files the messages shared stay in the user's OneDrive \
and stay shared.
- If a tool says sign-in is required, ask the user to run the quoted `teams-connector auth` command in \
a terminal; never attempt to sign in yourself. "Access denied" errors are about that item, not the \
sign-in.
- Do not call these tools in parallel; prefer one larger call over many small ones.
"""

READ_ONLY = ToolAnnotations(
    readOnlyHint=True, destructiveHint=False, idempotentHint=True, openWorldHint=False
)
LOCAL_FILE = ToolAnnotations(
    readOnlyHint=True, destructiveHint=False, idempotentHint=False, openWorldHint=False
)
SEND = ToolAnnotations(readOnlyHint=False, destructiveHint=True, idempotentHint=False, openWorldHint=True)

Since = Annotated[datetime | None, Field(description="Inclusive lower bound (ISO 8601; UTC if no offset).")]
Until = Annotated[datetime | None, Field(description="Inclusive upper bound (ISO 8601; UTC if no offset).")]
ConversationId = Annotated[str, Field(description="Conversation id from list_chats or search results.")]


def _logged[**P, R](function: Callable[P, Awaitable[R]]) -> Callable[P, Awaitable[R]]:
    """Log tool name, duration and outcome. Never arguments or results."""

    @functools.wraps(function)
    async def wrapped(*args: P.args, **kwargs: P.kwargs) -> R:
        started = time.monotonic()
        try:
            result = await function(*args, **kwargs)
        except Exception as exc:
            log.warning("tool %s failed (%s) in %dms", function.__name__, type(exc).__name__,
                        (time.monotonic() - started) * 1000)  # fmt: skip
            raise
        log.info("tool %s completed in %dms", function.__name__, (time.monotonic() - started) * 1000)
        return result

    return wrapped


def build_server(context: AppContext) -> FastMCP:
    mcp = FastMCP("lrh-teams-connector", instructions=INSTRUCTIONS, log_level="WARNING")

    async def services() -> Services:
        return await context.services()

    @mcp.tool(annotations=READ_ONLY)
    @_logged
    async def auth_status() -> dict[str, Any]:
        """Offline status: the signed-in account, each profile's cached credential and token expiry, and the
        sign-in command. Makes no network call; use it before a long task to see whether sign-in is needed."""
        return status_report(context.tokens)

    @mcp.tool(annotations=READ_ONLY)
    @_logged
    async def list_chats(
        refresh: Annotated[
            bool,
            Field(description="Refresh from Teams now (otherwise a cache up to 10 minutes old may answer)."),
        ] = False,  # fmt: skip
        limit: Annotated[int, Field(ge=1, le=200)] = 50,
        cursor: str | None = None,
        include_empty: Annotated[bool, Field(description="Include chats Teams reports as empty.")] = False,
        kind: Annotated[ChatKind | None, Field(description="Only this kind of conversation.")] = None,
    ) -> ChatPage:
        """Chats and channels, most recent activity first. coverage.complete is limited to coverage.scope."""
        return await (await services()).catalog.list(
            refresh=refresh, limit=limit, cursor=cursor, include_empty=include_empty, kind=kind
        )

    @mcp.tool(annotations=READ_ONLY)
    @_logged
    async def search_chats(
        query: Annotated[str, Field(description="Case-insensitive part of a chat or participant name.")],
        refresh: Annotated[bool, Field(description="Refresh the chat list first (recommended).")] = True,
        limit: Annotated[int, Field(ge=1, le=100)] = 25,
        cursor: str | None = None,
    ) -> ChatSearchResult:
        """Conversations whose name contains the query. With refresh (the default), also the named
        group and meeting chats that Teams matches by a member's name or email, with the members
        that matched."""
        return await (await services()).catalog.search(query, refresh=refresh, limit=limit, cursor=cursor)

    @mcp.tool(annotations=READ_ONLY)
    @_logged
    async def get_presence(conversation_id: ConversationId) -> PresenceResult:
        """Availability, activity, last-active time and device of the other person in a one-on-one chat.
        Nothing richer is returned: no status note and no calendar text. A failed read returns no presence
        and a reason."""
        return await (await services()).presence.for_chat(conversation_id)

    @mcp.tool(annotations=READ_ONLY)
    @_logged
    async def get_messages(
        conversation_id: ConversationId,
        since: Since = None,
        until: Until = None,
        message_limit: Annotated[
            int | None,
            Field(
                ge=1,
                description="Total latest messages to return across all pages "
                "(channels: of the most recently active threads).",
            ),
        ] = None,
        page_size: Annotated[int, Field(ge=1, le=50)] = 25,
        max_chars: Annotated[
            int,
            Field(
                ge=4_000,
                le=100_000,
                description="Text budget: whole messages up to this many characters, at least one.",
            ),
        ] = 30_000,
        cursor: Annotated[
            str | None,
            Field(description="Continuation; it restores the original options, which are then ignored."),
        ] = None,
        include_summaries: Annotated[
            bool,
            Field(
                description="Put Teams' AI summary after each transcribed meeting's marker, one read per "
                "meeting, within max_chars. It is generated by AI and can be wrong; "
                "the transcript is the record."
            ),
        ] = True,
    ) -> MessagePage:
        """One page of a conversation's history, oldest first within the page (a channel: threads by
        latest activity); the cursor continues with older messages. A transcribed meeting's marker is
        followed by Teams' AI summary of it unless include_summaries is false."""
        return await (await services()).history.get_messages(
            conversation_id,
            since=optional_utc(since),
            until=optional_utc(until),
            message_limit=message_limit,
            page_size=page_size,
            max_chars=max_chars,
            cursor=cursor,
            include_summaries=include_summaries,
        )

    @mcp.tool(annotations=READ_ONLY)
    @_logged
    async def search_messages(
        terms: Annotated[
            list[str] | None,
            Field(
                description="1 to 25 phrases; a message matches when ANY term matches (OR). Each term is "
                "one phrase: never split on its spaces, never read as query syntax, and no double quotes. "
                "Search v2 matches whole words and word prefixes: 'budget' also finds 'budgets', 'udget' "
                "finds nothing, and 'budget review' needs those words in that order. Omit only when "
                "continuing with a cursor."
            ),
        ] = None,
        conversation_ids: Annotated[
            list[str] | None,
            Field(description="Scope: up to 100 conversation ids from list_chats or search_chats."),
        ] = None,
        since: Since = None,
        until: Until = None,
        limit: Annotated[int, Field(ge=1, le=25, description="Hits per page, 1 to 25.")] = 25,
        cursor: str | None = None,
    ) -> MessageSearchResult:
        """Search Teams messages online through Microsoft Search v2, across all chats or within the chosen
        conversations and dates. Hits are pointers: message_id is the id get_messages reads, and
        conversation_id is set when it matches a known chat. total is approximate. Follow cursor only when
        more hits help; with a cursor, terms, scope and dates come from it."""
        return await (await services()).search.search_messages(
            terms,
            conversation_ids=conversation_ids,
            since=optional_utc(since),
            until=optional_utc(until),
            limit=limit,
            cursor=cursor,
        )

    @mcp.tool(annotations=READ_ONLY)
    @_logged
    async def search_transcripts(
        terms: Annotated[
            list[str],
            Field(
                description="1 to 25 phrases; an utterance matches when ANY term matches (OR). Each term is "
                "one phrase matched inside one utterance, on whole words and word prefixes, without case "
                "or accents, and never read as query syntax. No double quotes."
            ),
        ],
        conversation_ids: Annotated[
            list[str] | None,
            Field(
                description="Scope: up to 100 conversation ids from list_chats or search_chats. Their "
                "recordings are read in full. Omit to search across meetings (ranked, not complete)."
            ),
        ] = None,
        since: Since = None,
        until: Until = None,
        limit: Annotated[int, Field(ge=1, le=100, description="Matches to return, 1 to 100.")] = 25,
        include_summaries: Annotated[
            bool,
            Field(
                description="Include Teams' AI summary of each matched meeting once, in the result's "
                "summaries. It is generated by AI and can be wrong; the matches are the record."
            ),
        ] = True,
    ) -> TranscriptSearchResult:
        """Search the transcripts of meeting recordings for words said in the meeting. Each match names its
        meeting, conversation and recording message (message_id is the id get_messages reads), the speaker,
        the time into the recording, and the utterance. Read coverage: a result in conversations is complete
        unless a transcript could not be read or the limit was reached; a result across meetings is ranked
        and never complete. It counts videos that are not meetings, and those it could not place, apart. With
        include_summaries (on by default) it also lists Teams' AI summary of each matched meeting, once."""
        return await (await services()).transcript_search.search(
            terms,
            conversation_ids=conversation_ids,
            since=optional_utc(since),
            until=optional_utc(until),
            limit=limit,
            include_summaries=include_summaries,
        )

    @mcp.tool(annotations=LOCAL_FILE)
    @_logged
    async def export_chats(
        conversation_ids: Annotated[list[str], Field(min_length=1, max_length=500)],
        ctx: Context,
        since: Since = None,
        until: Until = None,
        message_limit: Annotated[int | None, Field(ge=1, description="Latest N messages per chat.")] = None,
        include_attachments: Annotated[
            bool,
            Field(description="Include selected message files and images beside the conversation export."),
        ] = True,
        include_transcripts: Annotated[
            bool,
            Field(
                description="Include the meeting transcripts of selected recordings, as text in the "
                "transcripts folder of the export. Enabled by default. When summaries suffice, set "
                "false and keep include_summaries=true; read summaries before full transcript files "
                "to save context tokens."
            ),
        ] = True,
        include_summaries: Annotated[
            bool,
            Field(
                description="Put Teams' AI summary of each selected meeting after its transcript marker. "
                "It is generated by AI and can be wrong; the transcript is the record."
            ),
        ] = True,
        format: Annotated[
            ExportFormat, Field(description="txt (for people) or jsonl (one JSON record per message).")
        ] = "txt",
    ) -> ExportArtifact:
        """Export selected conversations and return the local artifact path.

        One conversation with no attachment saved returns a plain text/JSONL file; anything else returns
        one ZIP with each conversation's file at its root and its attachments in a folder named after that
        file. Selected history is fetched from Teams first.
        """
        request = ExportRequest(
            conversation_ids=conversation_ids,
            since=optional_utc(since),
            until=optional_utc(until),
            message_limit=message_limit,
            format=format,
            include_attachments=include_attachments,
            include_transcripts=include_transcripts,
            include_summaries=include_summaries,
        )
        loop = asyncio.get_running_loop()
        pending: set[asyncio.Task[None]] = set()
        last: dict[str, tuple[str, int, int, int]] = {"step": ("", -1, -1, -1)}

        def progress(state: ExportProgress) -> None:
            step = (
                state.phase,
                state.chat_index,
                state.messages_retrieved // 500,
                state.attachments_downloaded + state.attachments_failed,
            )
            if step == last["step"]:
                return
            last["step"] = step
            text = (
                f"{state.phase}: chat {state.chat_index}/{state.chats_total}, "
                f"{state.messages_retrieved} messages, "
                f"{state.attachments_downloaded} attachments downloaded, "
                f"{state.attachments_failed} unavailable"
            )
            task = loop.create_task(ctx.report_progress(state.chat_index, state.chats_total, text))
            pending.add(task)
            task.add_done_callback(pending.discard)

        try:
            return await (await services()).exports.export(request, progress=progress)
        finally:
            if pending:
                await asyncio.gather(*pending, return_exceptions=True)

    @mcp.tool(annotations=LOCAL_FILE)
    @_logged
    async def download_attachment(
        conversation_id: ConversationId,
        message_id: Annotated[
            str | None, Field(description="The message's id, from get_messages or search_messages.")
        ] = None,
        sent_at: Annotated[
            datetime | None,
            Field(description="The message's time, exactly as the TXT export prints it, instead of its id."),
        ] = None,
        names: Annotated[
            list[str] | None,
            Field(
                description="The files to save, by the names their markers show; all of them when omitted."
            ),
        ] = None,
        include_summaries: Annotated[
            bool,
            Field(
                description="Include the meeting notes a Facilitator posts, read from the live Loop page. "
                "They are AI-generated; off leaves them out, as it leaves out the AI summaries."
            ),
        ] = True,
    ) -> DownloadedFiles:
        """Save the files a message names (shared files and pasted images) as local files and return their
        paths. Pass exactly one of message_id or sent_at. A file that cannot be fetched is listed under
        unavailable with its reason; the others are still saved. SharePoint pages ([Page: …]) are links.
        Meeting notes ([Meeting notes]) are read from the live Loop page and saved as text."""
        if (message_id is None) == (sent_at is None):
            raise InvalidRequest("Pass exactly one of message_id or sent_at.")
        when = optional_utc(sent_at) if sent_at is not None else None
        return await (await services()).files.download_attachments(
            conversation_id,
            message_id=message_id,
            sent_at=when,
            names=names,
            include_summaries=include_summaries,
        )

    @mcp.tool(annotations=SEND)
    @_logged
    async def send_message(
        conversation_id: ConversationId,
        expected_chat_name: Annotated[
            str, Field(description="The chat's exact current name from list_chats; checked before sending.")
        ],
        text: Annotated[
            str | None,
            Field(description="Plain text, up to 10,000 characters; HTML characters are escaped. Or html."),
        ] = None,
        html: Annotated[
            str | None,
            Field(
                description="HTML, up to 10,000 characters, sent as written (bold, lists, links, code). "
                'Active content and unfinished markup are refused; <img src="file name"> places one of '
                "images, any other image is refused. Pass exactly one of text or html (with files or images, "
                "both may be omitted)."
            ),
        ] = None,
        files: Annotated[
            list[str] | None,
            Field(
                description="Absolute paths of local files to attach, in one-on-one and group chats and the "
                "self chat: up to 10, each up to 2 GiB (config.MAX_SEND_FILE_BYTES). They are uploaded to "
                "your OneDrive and shared with the chat's other members before the message is posted."
            ),
        ] = None,
        images: Annotated[
            list[str] | None,
            Field(
                description="Absolute paths of PNG or JPEG images to show inline (same chats as files), up "
                'to 10 with distinct file names, about 3 MB in total. In html, <img src="file name"> places '
                "one; the others follow the text. Other formats or larger images are refused: send them in "
                "files."
            ),
        ] = None,
    ) -> SendResult:
        """Send one message to a chat or channel, as plain text or as HTML sent as written, optionally with
        files and inline images. External side effect: only with the user's explicit authorization for this
        recipient, the content, every file and every image. Never resent after an uncertain outcome. If an
        upload, share or the post fails, the files already uploaded are deleted again (unless the message
        may have been posted), and the error says what was deleted and what is left."""
        return await (await services()).sender.send(
            conversation_id,
            expected_chat_name=expected_chat_name,
            text=text,
            html=html,
            files=files,
            images=images,
        )

    @mcp.tool(annotations=SEND)
    @_logged
    async def delete_messages(
        conversation_id: ConversationId,
        expected_chat_name: Annotated[
            str, Field(description="The chat's exact current name from list_chats; checked before deleting.")
        ],
        message_ids: Annotated[
            list[str],
            Field(description="Ids from get_messages of the user's own messages to delete, up to 100."),
        ],
    ) -> DeleteResult:
        """Delete a set of the user's own messages in one chat (not channels), as Teams' Delete does.
        External side effect: call only after listing the set to the user (chat, count, first and last
        message) and getting one explicit confirmation for it; this tool cannot check that confirmation.
        Each message is read again first: anyone else's message, a system event or an already deleted one
        is skipped. A delete is never resent after an uncertain outcome. The result lists deleted, skipped and
        uncertain messages; files they shared are named and stay in your OneDrive, still shared."""
        return await (await services()).deleter.delete(
            conversation_id, expected_chat_name=expected_chat_name, message_ids=message_ids
        )

    return mcp


def run(*, unsecure: bool) -> None:
    build_server(AppContext(unsecure=unsecure)).run("stdio")
