"""Exports with Teams' AI summaries: the summary after each transcript marker, the include_summaries
flag, history reads that fetch no summary, and a summary that cannot be read. Through the real exports
service and the fake tenant. Synthetic meetings only."""

from __future__ import annotations

import zipfile
from pathlib import Path

from teams_connector.bootstrap import Services
from teams_connector.domain.models import ExportRequest
from tests.fakes.teams_fake import FakeTeams, add_meeting, synthetic_drive

CHAT = "19:one@unq.gbl.spaces"
DRIVE = synthetic_drive(
    "11111111-2222-3333-4444-555555555555",
    "66666666-7777-8888-9999-aaaaaaaaaaaa",
    "bbbbbbbb-cccc-dddd-eeee-ffffffffffff",
)
LABEL = "AI summary from Teams (generated by AI; may be inaccurate):"
UNAVAILABLE = "AI summary from Teams could not be read."
SUMMARY = "Synthetic summary: the deployment moves to Friday."
DOCUMENT = {
    "entries": [
        {
            "speakerDisplayName": "Synthetic Ann",
            "startOffset": "00:00:17.6950000",
            "text": "Good morning.",
            "spokenLanguageTag": "en-us",
        }
    ],
    "events": [],
}


def _request(**changes: object) -> ExportRequest:
    values: dict[str, object] = {"conversation_ids": [CHAT], "format": "txt"}
    values.update(changes)
    return ExportRequest.model_validate(values)


def _conversation(path: Path) -> str:
    """The conversation's text: the plain file, or the ZIP's file at its root."""
    if not zipfile.is_zipfile(path):
        return path.read_text(encoding="utf-8")
    with zipfile.ZipFile(path) as archive:
        name = next(member for member in archive.namelist() if member.endswith(".txt") and "/" not in member)
        return archive.read(name).decode("utf-8")


def _meeting(fake: FakeTeams, *, item: str, summary: str | None) -> None:
    add_meeting(
        fake,
        chat_id=CHAT,
        title="Synthetic Standup",
        when="2026-09-04T10:00:00Z",
        drive=DRIVE,
        item=item,
        transcript_id=f"t-{item}",
        document=DOCUMENT,
        summary=summary,
    )


async def test_the_summary_follows_the_transcript_marker(services: Services, fake: FakeTeams) -> None:
    _meeting(fake, item="01SM1", summary=SUMMARY)
    await services.catalog.refresh()

    artifact = await services.exports.export(_request())

    text = _conversation(Path(artifact.path))
    assert text.index("[Transcript: Synthetic Standup]") < text.index(LABEL) < text.index(SUMMARY)
    assert len(fake.summary_reads) == 1
    assert fake.summary_reads[0].endswith("_01SM1")


async def test_reading_history_fetches_no_summary(services: Services, fake: FakeTeams) -> None:
    _meeting(fake, item="01SM2", summary=SUMMARY)
    await services.catalog.refresh()
    chat = await services.catalog.get(CHAT)

    texts = [
        message.text
        async for page in services.history.selection(chat, since=None, until=None, message_limit=None)
        for message in page
    ]

    assert any("[Transcript: Synthetic Standup]" in text for text in texts)
    assert not any(LABEL in text or SUMMARY in text for text in texts)
    assert fake.summary_reads == []


async def test_the_flag_leaves_summaries_out(services: Services, fake: FakeTeams) -> None:
    _meeting(fake, item="01SM3", summary=SUMMARY)
    await services.catalog.refresh()

    artifact = await services.exports.export(_request(include_summaries=False))

    text = _conversation(Path(artifact.path))
    assert "[Transcript: Synthetic Standup]" in text
    assert LABEL not in text and SUMMARY not in text
    assert fake.summary_reads == []


async def test_without_the_transcript_file_the_marker_says_so_and_keeps_the_summary(
    services: Services, fake: FakeTeams
) -> None:
    _meeting(fake, item="01SM4", summary=SUMMARY)
    await services.catalog.refresh()

    artifact = await services.exports.export(_request(include_transcripts=False, include_attachments=False))

    assert artifact.filename.endswith(".txt")
    text = Path(artifact.path).read_text(encoding="utf-8")
    assert "[Transcript not included: Synthetic Standup]" in text
    assert SUMMARY in text
    assert "[Transcript: " not in text


async def test_a_summary_that_cannot_be_read_is_said_so_and_the_export_goes_on(
    services: Services, fake: FakeTeams
) -> None:
    _meeting(fake, item="01SM5", summary=SUMMARY)
    await services.catalog.refresh()
    fake.summary_status = 403

    artifact = await services.exports.export(_request())

    with zipfile.ZipFile(Path(artifact.path)) as archive:
        members = archive.namelist()
    assert any(member.endswith("/transcripts/Synthetic Standup.txt") for member in members)
    text = _conversation(Path(artifact.path))
    assert "[Transcript: Synthetic Standup]" in text
    assert UNAVAILABLE in text
    assert LABEL not in text


async def test_a_meeting_without_a_summary_keeps_its_marker_alone(
    services: Services, fake: FakeTeams
) -> None:
    _meeting(fake, item="01SM6", summary=None)
    await services.catalog.refresh()

    artifact = await services.exports.export(_request())

    text = _conversation(Path(artifact.path))
    assert "[Transcript: Synthetic Standup]" in text
    assert LABEL not in text and UNAVAILABLE not in text
    assert len(fake.summary_reads) == 1
